import type { Template } from "./types";

export type TrainedMap = Record<string, Template[]>;
export const SIGNATURES_PATH = "src/signing/gestureSignatures.ts";

/** Source text of src/signing/gestureSignatures.ts for a set of trained examples. */
export function renderSignaturesFile(map: TrainedMap): string {
  const round = (rows: number[][]) => rows.map((r) => r.map((v) => Math.round(v * 1e4) / 1e4));
  const body = Object.keys(map).sort().map((lang) => {
    const items = map[lang].map((t) => "    " + JSON.stringify({ id: t.id, label: t.label, source: "user", ...(t.origin ? { origin: t.origin } : {}), rows: round(t.rows) }));
    return `  ${JSON.stringify(lang)}: [\n${items.join(",\n")}${items.length ? "\n" : ""}  ]`;
  }).join(",\n");
  return `/**
 * gestureSignatures.ts — permanently saved training examples for video → sign recognition.
 *
 * GENERATED by the Sign Capture page (/record-gesture → "Save to gestureSignatures.ts") and by
 * scripts/import-esl-videos.ts. You can also edit it by hand, but numbers are feature vectors
 * (see src/signing/recognition/features.ts), not something to type in. Each example is
 * STEPS × FEATURE_DIM numbers: finger curl/spread/pinch, palm direction, hand position relative to
 * the signer's body, and the other hand. Only numbers are stored, never video or images.
 *
 * Avatar-derived templates are generated at run time for every sign the avatar can perform; the
 * examples below are added on top and count for more because they come from real people.
 */
import type { Template } from "./recognition/types";

export const TRAINED_TEMPLATES: Record<string, Template[]> = {
${body}
};
`;
}
